/**
 * Generates the P06a browser checkpoint fixture.
 *
 * The fixture stands in for a real P05b export: it uses the exact P05a manifest
 * shape written by `training/vector_nca/core.py::save_checkpoint`, with weights
 * drawn from a deterministic seeded generator instead of a training run. That
 * is enough to prove the loader, checksum, shape, and runtime contracts without
 * requiring PyTorch in CI.
 *
 *   node scripts/generate-checkpoint-fixture.mjs
 *
 * Re-running must reproduce the committed file byte for byte.
 */
import { createHash } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const OUT_PATH = join(
  dirname(fileURLToPath(import.meta.url)),
  '../src/nca/models/p06a-reference-checkpoint.json',
);

// Matches training/configs/reference.yaml.
const LATENT_CHANNELS = 16;
const SENSOR_CHANNELS = 6;
const HIDDEN_WIDTH = 64;
const UPDATE_RATE = 0.5;
const TRAINING_SEED = 240807;
const WEIGHT_SEED = 20260808;

/** Same generator as src/simulation/prng.ts, so fixtures stay reproducible. */
function makeRandom(seed) {
  let state = seed >>> 0;
  return () => {
    state = (state + 0x6d2b79f5) >>> 0;
    let value = state;
    value = Math.imul(value ^ (value >>> 15), value | 1);
    value ^= value + Math.imul(value ^ (value >>> 7), value | 61);
    return ((value ^ (value >>> 14)) >>> 0) / 4294967296;
  };
}

const random = makeRandom(WEIGHT_SEED);
const signed = () => random() * 2 - 1;

const inputWidth = LATENT_CHANNELS * 2 + SENSOR_CHANNELS;
const shapes = {
  'net.0.weight': [HIDDEN_WIDTH, inputWidth],
  'net.0.bias': [HIDDEN_WIDTH],
  'net.2.weight': [LATENT_CHANNELS, HIDDEN_WIDTH],
  'net.2.bias': [LATENT_CHANNELS],
};

// Kaiming-ish scaling keeps the untrained fixture bounded over long rollouts.
const scales = {
  'net.0.weight': Math.sqrt(2 / inputWidth) * 0.6,
  'net.0.bias': 0.02,
  'net.2.weight': Math.sqrt(2 / HIDDEN_WIDTH) * 0.35,
  'net.2.bias': 0.02,
};

const names = Object.keys(shapes).sort();
const values = [];
const tensors = [];

for (const name of names) {
  const count = shapes[name].reduce((total, dimension) => total * dimension, 1);
  tensors.push({ name, shape: shapes[name], offset: values.length });
  for (let index = 0; index < count; index += 1) {
    values.push(Math.fround(signed() * scales[name]));
  }
}

const payload = Float32Array.from(values);
const bytes = new Uint8Array(payload.buffer, payload.byteOffset, payload.byteLength);
const payloadSha256 = createHash('sha256').update(bytes).digest('hex');
const payloadBase64 = Buffer.from(bytes).toString('base64');

// `sha256` in the manifest is the source .pt checksum. There is no .pt here, so
// the fixture records the checksum of its own payload under a fixture version.
const container = {
  container: 'vector-nca-browser.v1',
  manifest: {
    architecture: 'vector_nca_mlp_v1',
    checkpoint_version: 'p06a-fixture-v1',
    dtype: 'float32',
    hidden_width: HIDDEN_WIDTH,
    intended_use: 'P06a browser loader and CPU reference kernel contract validation',
    latent_channels: LATENT_CHANNELS,
    limitations: [
      'Deterministic fixture weights, not a trained checkpoint; no phenotype quality is implied.',
      'Generated by scripts/generate-checkpoint-fixture.mjs rather than a PyTorch training run.',
    ],
    metrics: {},
    phenotype: 'branching',
    schema_version: 1,
    sensor_channels: SENSOR_CHANNELS,
    sha256: payloadSha256,
    training_seed: TRAINING_SEED,
    update_rate: UPDATE_RATE,
  },
  payloadBase64,
  payloadSha256,
  tensors,
  updateRate: UPDATE_RATE,
};

writeFileSync(OUT_PATH, `${JSON.stringify(container, null, 2)}\n`);
console.log(`wrote ${OUT_PATH}`);
console.log(`  floats: ${payload.length}`);
console.log(`  payload sha256: ${payloadSha256}`);
